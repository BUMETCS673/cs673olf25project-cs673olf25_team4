import os
from typing import Optional

import uvicorn
from fastapi import FastAPI, HTTPException, APIRouter, Query
from pydantic import BaseModel, ValidationError
from groq import Groq
from starlette.concurrency import run_in_threadpool

import logging

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger(__name__)


class ConcertExtraction(BaseModel):
    location: str
    start_date: str
    end_date: str
    artist: str


class TokenResponse(BaseModel):
    location: str
    start_date: str
    end_date: str
    artist: str


class SummaryResponse(BaseModel):
    summary: str
    model: str
    prompt_tokens: Optional[int] = None
    completion_tokens: Optional[int] = None
    total_tokens: Optional[int] = None


class GroqService:
    def __init__(self) -> None:
        self.router = APIRouter()
        self.client: Optional[Groq] = None

        # Routes
        self.router.add_api_route(
            "/",
            self.root,
            methods=["GET"],
        )
        self.router.add_api_route(
            "/get_tokens",
            self.get_tokens,
            methods=["GET"],
            response_model=TokenResponse,
        )
        self.router.add_api_route(
            "/get_summary",
            self.get_summary,
            methods=["GET"],
            response_model=SummaryResponse,
        )

    async def root(self):
        """Health check endpoint."""
        return {"status": "ok", "message": "Groq service is running."}

    async def get_tokens(self, user_input: str = Query(...)) -> TokenResponse:
        """
        Extract tokens (location, dates, artist) from user input about a music event.
        """
        logger.info("Received token count request")
        client = self._ensure_client()

        chat_completion = await run_in_threadpool(
            client.chat.completions.create,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are an extractor.\n"
                        "Fields:\n"
                        "- location\n"
                        "- start_date\n"
                        "- end_date\n"
                        "- artist\n\n"
                        "Rules:\n"
                        "- Dates: ddMMyyyy (e.g., 05082025).\n"
                        "- One date → same start/end.\n"
                        "- Date range → set both.\n"
                        "- Week → Mon as start, Sun as end.\n"
                        "  Examples: 'week 42 of 2025', 'week of 12 May 2026'.\n"
                        "- Month+year → first to last day.\n"
                        "- Year only → 0101YYYY to 3112YYYY.\n"
                        '- Missing/unclear → "unknown".\n'
                        "- No extra details allowed.\n\n"
                        "Output:\n"
                        "- Exactly one JSON line.\n"
                        "- Only the tokens, nothing else.\n"
                        '{"location":"...","start_date":"...",\n'
                        '"end_date":"...","artist":"..."}'
                    ),
                },
                {"role": "user", "content": user_input},
            ],
            model="groq/compound",
            temperature=0.0,
        )

        content = chat_completion.choices[0].message.content.strip()
        logger.debug(f"Model raw output: {content}")

        try:
            data = ConcertExtraction.model_validate_json(content)
            return TokenResponse(**data.model_dump())
        except ValidationError:
            logger.warning("Schema validation failed for model output: %s", content)
            return TokenResponse(
                location="unknown",
                start_date="unknown",
                end_date="unknown",
                artist="unknown",
            )

